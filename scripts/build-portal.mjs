// Package the approved game for a CrazyGames Basic Launch evaluation.
// This does not publish a game, enable ads, or change the production build.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
execFileSync(process.execPath, [path.join(root, 'scripts/build-release.mjs'), '--check'], {stdio:'inherit'});
let html = await readFile(path.join(root, 'one-off-itch.html'), 'utf8');
const outgoing = '\\nhttps://lcsmith2009.github.io/one-off-game/';
if (!html.includes(outgoing)) throw new Error('Review the source share URL before building the portal variant.');
html = html.replace(outgoing, '');
const css = `
/* Portal-only layout: keep primary actions visible in short landscape frames. */
body{user-select:none;-webkit-user-select:none}
input,textarea{user-select:text;-webkit-user-select:text}
@media(min-width:700px) and (max-height:750px){
 .shell{width:min(100%,720px);padding:10px 24px 18px}header{height:44px}
 .screen{padding-top:8px}.eyebrow{margin:4px 0 8px}
 #home h1{font-size:42px;margin:8px 0}.lede{font-size:16px;line-height:1.4;margin:10px 0}
 .rule-card{margin:12px 0;padding:12px}.target-demo{height:50px;min-width:58px}
 .primary,.secondary{height:44px;margin-top:8px;border-radius:12px}
 .mini-stats{margin-top:12px}.mini-stats div{padding:8px 4px}.mini-stats b{font-size:18px}
 footer{margin-top:4px}.privacy-details summary{padding:6px}.target-wrap{margin:10px 0 6px}
 .target-wrap strong{font-size:62px}#instruction{min-height:32px;margin:8px 0;font-size:15px}
 .choice-grid{margin-top:10px;gap:8px}.choice{height:52px;font-size:26px}
 .number-input{height:56px;font-size:32px}.slider-wrap{margin:10px 0 6px}.slider-label{font-size:28px;margin-bottom:0}
 .flash{height:88px;margin-top:8px}.feedback{min-height:28px;margin-top:8px;font-size:17px}
 .score-ring{height:100px;width:100px;border-width:7px;margin:8px auto}.score-ring b{font-size:30px}
 .result-title{font-size:28px;margin:6px 0}.result-grid{margin:10px 0}.result-box{height:28px;width:36px}
 #game>p{margin:8px 0;font-size:14px}.record-line{margin:6px 0}
}
`;
html = html.replace('</style>', css + '\n</style>');
html = html.replace('<!-- Generated by scripts/build-release.mjs.', '<!-- Portal evaluation variant generated by scripts/build-portal.mjs. Source: scripts/build-release.mjs.');
if (/https?:\/\//.test(html)) throw new Error('Review unexpected external URLs before packaging.');
const out = path.join(root, 'dist', 'portal');
await mkdir(out, {recursive:true});
await writeFile(path.join(out,'index.html'),html);
execFileSync('python3',['-c',`from pathlib import Path
from zipfile import ZipFile,ZipInfo,ZIP_DEFLATED
p=Path(${JSON.stringify(out)})
i=ZipInfo('index.html',(2026,10,22,0,0,0));i.compress_type=ZIP_DEFLATED;i.external_attr=0o644<<16
with ZipFile(p.parent/'one-off-crazygames-basic.zip','w') as z:z.writestr(i,(p/'index.html').read_bytes())
`]);
await mkdir(path.join(root,'release','portal'),{recursive:true});
await writeFile(path.join(root,'release','portal','one-off-crazygames-basic.zip'),await readFile(path.join(root,'dist','one-off-crazygames-basic.zip')));
console.log('Portal evaluation package: dist/one-off-crazygames-basic.zip; no ads/SDK/publishing.');
