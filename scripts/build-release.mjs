import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFile(path.join(root, file), 'utf8');
const [home, play, css, core, app, game, privacy] = await Promise.all(['index.html','v2.html','style.css','core.js','app.js','play-v2.js','privacy.html'].map(read));
const section = play.match(/<section[\s\S]*?<\/section>/)[0].replace('screen active', 'screen');
const privacyCopy = privacy.match(/<p class="lede">[\s\S]*?(?=<a class="secondary")/)[0];
let standalone = home.replace('<body>', '<body data-standalone="true">')
  .replace(/<link rel="stylesheet"[^>]+>/, '<style>' + css + '\n.privacy-details{font-size:12px;color:#a0a8b8;text-align:left}.privacy-details summary{text-align:center;cursor:pointer;padding:12px}.privacy-details .lede{font-size:13px}</style>')
  .replace(/<link rel="manifest"[^>]+>\n?/, '')
  .replace('</header>', '<a id="gameHome" class="icon-btn hidden" href="?" aria-label="Home">⌂</a></header>')
  .replace('./v2.html?mode=daily&amp;build=20', '?mode=daily')
  .replace('./v2.html?mode=practice&amp;build=20', '?mode=practice')
  .replace('<a href="./privacy.html">Privacy</a>', '<details class="privacy-details"><summary>Privacy</summary>' + privacyCopy + '</details>')
  .replace('<dialog id="modal"', section + '\n<dialog id="modal"')
  .replace(/<script src="[^"\n]+" defer><\/script>\n?/g, '');
const boot = `const playing = new URLSearchParams(location.search).has('mode');
if (playing) {
  document.getElementById('home').classList.remove('active');
  document.getElementById('game').classList.add('active');
  document.getElementById('statsBtn').classList.add('hidden');
  document.getElementById('gameHome').classList.remove('hidden');
}`;
standalone = standalone.replace('</body>', '<!-- Generated by scripts/build-release.mjs. Edit source files, then rebuild. -->\n<script>\n' + core + '\n' + app + '\n' + boot + '\nif (playing) {\n' + game + '\n}\n</script>\n</body>');
if (process.argv.includes('--check')) {
  if (await read('one-off-itch.html') !== standalone) throw new Error('Stale itch.io build. Run npm run build.');
  console.log('Standalone matches the current production source.');
} else {
  await writeFile(path.join(root, 'one-off-itch.html'), standalone);
  await mkdir(path.join(root, 'dist', 'itch'), { recursive: true });
  await writeFile(path.join(root, 'dist', 'itch', 'index.html'), standalone);
  await copyFile(path.join(root, 'one-off-itch.html'), path.join(root, 'dist', 'one-off-itch.html'));
  execFileSync('python3', ['-c', `from pathlib import Path
from zipfile import ZipFile,ZipInfo,ZIP_DEFLATED
root=Path(${JSON.stringify(root)})
info=ZipInfo('index.html',(2026,10,18,0,0,0))
info.compress_type=ZIP_DEFLATED
info.external_attr=0o644<<16
with ZipFile(root/'dist'/'one-off-itch.zip','w') as z:z.writestr(info,(root/'dist'/'itch'/'index.html').read_bytes())
`]);
  console.log('Build 20 ready: dist/one-off-itch.zip and dist/one-off-itch.html');
}
